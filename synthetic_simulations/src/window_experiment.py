"""Effect of aggregating snapshots over time windows, of the history parameter
and of absorption on MajorTrack, for the synthetic scenarios generated by main.R.

For each scenario, window size w, history h (in windows) and absorption on/off:
  1. Aggregate the T=100 interaction snapshots into floor(T/w) windows: the
     weight of edge (i,j) in a window is the number of snapshots of the window
     in which i and j interacted (in either direction). Trailing snapshots
     that do not fill a complete window are discarded.
  2. Detect static communities in each window with weighted Leiden
     (modularity, fixed seed).
  3. Run MajorTrack on the series of windows, using either these groups
     ('leiden') or the true partition of each window ('oracle').
  4. Compute:
     - accuracy against the ground truth at the resolution of the original
       time steps (each step takes the label of its window): mean per-step
       NMI, global NMI with the truth, and global NMI with reference DCs
       obtained by running MajorTrack on the true partitions (this removes the
       dependence on the convention used to name merged groups in the truth);
     - number of DCs and total consistency C_tot (mean over DCs of the mean
       Jaccard similarity of the DC members between consecutive windows);
     - parsimony of the DC structure: number of distinct inter-DC connections
       (element flows between different DCs) per window transition, split in
       merges, splits and shifts;
     - event detection against the true events: events are connected
       components of the flows between groups at a transition, matched through
       the member sets involved, with a temporal tolerance of one window.

Results: data/<scenario>/window_results/metrics_windows.csv and
data/window_summary.csv.

Usage (from synthetic_simulations/):
  python src/window_experiment.py [substring ...]
"""
import glob
import os
import sys
import warnings
from collections import Counter

import igraph as ig
import leidenalg
import numpy as np
import pandas as pd
from scipy.optimize import linear_sum_assignment
from sklearn.metrics import normalized_mutual_info_score

warnings.filterwarnings('ignore', category=SyntaxWarning)
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from run_majortrack import DIR_DATA, SEED, read_scenario  # noqa: E402
from majortrack import MajorTrack  # noqa: E402

WINDOWS = [1, 2, 4, 5, 6, 8, 10, 12, 15, 20, 25]
HISTORIES = [1, 2, 3, 5, 10]          # in units of windows
ABSORPTION = [True, False]


def aggregate(mats, w):
    k = len(mats) // w
    sym = [((m + m.T) > 0).astype(int) for m in mats[:k * w]]
    return [sum(sym[j * w:(j + 1) * w]) for j in range(k)]


def static_communities(adj, seed):
    g = ig.Graph.Weighted_Adjacency(adj.tolist(), mode='upper', attr='weight', loops=False)
    part = leidenalg.find_partition(g, leidenalg.ModularityVertexPartition,
                                    weights='weight', seed=seed)
    return np.array(part.membership)


def run_majortrack(groupings, n, history, absorption):
    clusterings = [[set(np.flatnonzero(lab == c).tolist()) for c in np.unique(lab)]
                   for lab in groupings]
    mt = MajorTrack(clusterings=clusterings,
                    individuals=[set(range(n)) for _ in clusterings],
                    history=history)
    mt.get_group_matchup('fraction')
    mt.get_dcs(absorption=absorption)
    mt.get_community_membership()
    mt.get_individual_membership()
    return np.array([[mt.individual_membership[t][i] for i in range(n)]
                     for t in range(len(clusterings))])


def window_truth(truth, w):
    """Ground truth at window resolution: modal label of each element."""
    k = truth.shape[0] // w
    return np.array([[Counter(truth[j * w:(j + 1) * w, i]).most_common(1)[0][0]
                      for i in range(truth.shape[1])] for j in range(k)])


def consistency(labels):
    """Total consistency C_tot and fraction of DCs present in a single window.
    C_mu is the mean Jaccard similarity of the members of DC mu between
    consecutive windows in which it is present; C_tot is the mean of C_mu over
    the DCs present in at least two consecutive windows."""
    pairs = {}
    for t in range(1, len(labels)):
        for c in set(labels[t]) & set(labels[t - 1]):
            a, b = labels[t - 1] == c, labels[t] == c
            pairs.setdefault(c, []).append((a & b).sum() / (a | b).sum())
    cmu = [np.mean(v) for v in pairs.values()]
    n_dc = len(np.unique(labels))
    return (np.mean(cmu) if cmu else np.nan), 1 - len(cmu) / n_dc


def connections(labels):
    """Distinct inter-DC connections at each transition, classified as
    merge (source DC absent after the transition), split (target DC absent
    before) or shift (both DCs present before and after)."""
    out = []
    for t in range(1, len(labels)):
        prev, nxt = set(labels[t - 1]), set(labels[t])
        edges = {(a, b) for a, b in zip(labels[t - 1], labels[t]) if a != b}
        merges = sum(a not in nxt for a, b in edges)
        splits = sum(b not in prev and a in nxt for a, b in edges)
        out.append((len(edges), merges, splits, len(edges) - merges - splits))
    return np.array(out) if out else np.zeros((0, 4))


def event_signatures(labels, times):
    """Label-free description of the events at every transition. The flows of
    elements between the DCs before and after a transition form a bipartite
    graph; each connected component that contains at least one flow between
    different DCs is an event (a merge, a split, a shift, or a combination).
    An event is described by its time and by the member sets of the DCs
    involved before and after the transition, so that it does not depend on
    which DC keeps its identity."""
    sig = []
    for k in range(1, len(labels)):
        prev, nxt = labels[k - 1], labels[k]
        parent = {}

        def find(x):
            while parent.setdefault(x, x) != x:
                x = parent[x]
            return x
        for a, b in set(zip(prev, nxt)):
            parent[find(('pre', a))] = find(('post', b))
        comps = {}
        for a, b in set(zip(prev, nxt)):
            comps.setdefault(find(('pre', a)), set()).update({('pre', a), ('post', b)})
        for nodes in comps.values():
            pre = [x[1] for x in nodes if x[0] == 'pre']
            post = [x[1] for x in nodes if x[0] == 'post']
            if sorted(pre) == sorted(post) and len(pre) == 1:
                continue  # identity flow only
            sig.append((times[k],
                        [frozenset(np.flatnonzero(prev == a)) for a in pre],
                        [frozenset(np.flatnonzero(nxt == b)) for b in post]))
    return sig


def _jac(x, y):
    return 1.0 if not x and not y else len(x & y) / len(x | y)


def _sets_match(p, q, thr):
    """True if the two collections of sets can be paired one-to-one with
    Jaccard similarity >= thr for every pair."""
    if len(p) != len(q):
        return False
    sim = np.array([[_jac(x, y) for y in q] for x in p])
    r, c = linear_sum_assignment(-sim)
    return bool((sim[r, c] >= thr).all())


def _match(e, f, tol, thr=0.5):
    return abs(e[0] - f[0]) <= tol and _sets_match(e[1], f[1], thr) and \
        _sets_match(e[2], f[2], thr)


def event_detection(dc_win, w, true_sig):
    """Precision, recall and F1 of the inferred events with respect to the
    true events. An inferred event matches a true event if it occurs within
    one window of it and the member sets involved before and after the
    transition can be paired one-to-one with Jaccard similarity >= 0.5."""
    t_max = len(dc_win) * w
    true_sig = [e for e in true_sig if e[0] < t_max]
    inf_sig = event_signatures(dc_win, [k * w for k in range(len(dc_win))])
    m_inf = sum(any(_match(e, f, w) for f in true_sig) for e in inf_sig)
    m_true = sum(any(_match(f, e, w) for e in inf_sig) for f in true_sig)
    prec = m_inf / len(inf_sig) if inf_sig else np.nan
    rec = m_true / len(true_sig) if true_sig else np.nan
    f1 = 2 * prec * rec / (prec + rec) if inf_sig and prec + rec > 0 else 0.0
    return prec, rec, f1, len(inf_sig), len(true_sig)


def accuracy(dc_win, truth, w, valid, ref=None):
    """Mean per-step NMI and global NMI with the ground truth and, if given,
    global NMI with a reference labelling of the same elements x steps."""
    lab = np.repeat(dc_win, w, axis=0)
    tr, v = truth[:len(lab)], valid[:len(lab)]
    step = np.nanmean([normalized_mutual_info_score(tr[t], lab[t])
                       for t in range(len(lab)) if v[t]])
    glob_ = normalized_mutual_info_score(tr[v].ravel(), lab[v].ravel())
    if ref is None:
        return step, glob_
    return step, glob_, normalized_mutual_info_score(ref[:len(lab)][v].ravel(), lab[v].ravel())


def analyse(folder):
    label, mats, truth = read_scenario(folder)
    n = truth.shape[1]
    valid = np.array([len(np.unique(x)) > 1 for x in truth])
    true_sig = event_signatures(truth, list(range(len(truth))))
    # reference DCs: MajorTrack on the true partitions at step resolution. They
    # reproduce the planted groups and events, but follow MajorTrack's identity
    # convention (a merged group inherits the identity of its majority
    # contributor), which differs from the convention used to label the truth
    ref = run_majortrack(truth, n, 1, True)
    out = os.path.join(folder, 'window_results')
    os.makedirs(out, exist_ok=True)
    rows = []
    for w in WINDOWS:
        wins = aggregate(mats, w)
        static = np.array([static_communities(a, SEED + j) for j, a in enumerate(wins)])
        pd.DataFrame(static.T).to_csv(os.path.join(out, f'static_w-{w}.csv'), index_label='node')
        tw = window_truth(truth, w)
        con_t = connections(tw)
        base = dict(scenario=label, window=w, n_windows=len(wins),
                    true_conn_per_transition=con_t[:, 0].mean() if len(con_t) else np.nan,
                    true_C_tot=consistency(tw)[0], true_n_groups=len(np.unique(tw)))
        # 'leiden': groups detected in the aggregated windows; 'oracle': true
        # (modal) partition of each window, which isolates the tracking step
        for source, groups in (('leiden', static), ('oracle', tw)):
            st_step, _ = accuracy(groups, truth, w, valid)
            for h in HISTORIES:
                if h > len(wins) - 1 and h > 1:
                    continue
                for ab in ABSORPTION:
                    dc = run_majortrack(groups, n, h, ab)
                    step, glob_, glob_ref = accuracy(dc, truth, w, valid, ref)
                    ctot, single = consistency(dc)
                    con = connections(dc)
                    prec, rec, f1, n_inf, n_true = event_detection(dc, w, true_sig)
                    rows.append(dict(
                        base, input=source, history=h, history_steps=h * w, absorption=ab,
                        n_static_groups_mean=np.mean([len(np.unique(g)) for g in groups]),
                        static_step_NMI=st_step, mean_step_NMI=step,
                        global_NMI=glob_, global_NMI_ref=glob_ref, n_dcs=len(np.unique(dc)),
                        C_tot=ctot, frac_single_window_dcs=single,
                        conn_per_transition=con[:, 0].mean() if len(con) else np.nan,
                        merges_per_transition=con[:, 1].mean() if len(con) else np.nan,
                        splits_per_transition=con[:, 2].mean() if len(con) else np.nan,
                        shifts_per_transition=con[:, 3].mean() if len(con) else np.nan,
                        event_precision=prec, event_recall=rec, event_F1=f1,
                        n_inferred_events=n_inf, n_true_events=n_true))
                    if source == 'leiden':
                        pd.DataFrame(dc.T).to_csv(
                            os.path.join(out, f'dc_w-{w}_h-{h}_abs-{int(ab)}.csv'),
                            index_label='node')
        print(f'  {label} w={w} done', flush=True)
    df = pd.DataFrame(rows)
    df.to_csv(os.path.join(out, 'metrics_windows.csv'), index=False)
    return df


if __name__ == '__main__':
    folders = sorted(f for f in glob.glob(os.path.join(DIR_DATA, 'problem_*')) if os.path.isdir(f))
    selected = sys.argv[1:]
    for f in folders:
        if selected and not any(s in os.path.basename(f) for s in selected):
            continue
        print('analysing', os.path.basename(f), flush=True)
        analyse(f)
    done = [os.path.join(f, 'window_results', 'metrics_windows.csv') for f in folders]
    df = pd.concat([pd.read_csv(p) for p in done if os.path.exists(p)], ignore_index=True)
    df.to_csv(os.path.join(DIR_DATA, 'window_summary.csv'), index=False)
